`timescale 1ns/1ps
`default_nettype none

import m68882_cir_pkg::*;
import m68882_apu_pkg::*;

// Phase 4a test: register-to-register FADD/FSUB, driven through the real
// Command CIR dialog (opclass 000) rather than calling m68882_apu_pkg's
// own fp_add_sub task directly -- this confirms the full path (command
// word decode -> APU -> register file write -> FPSR update), not just
// the arithmetic core in isolation.
//
// Test operands are known-good IEEE-754-consistent extended-precision
// bit patterns (Table 3-3's own layout), computed independently in
// Python and cross-checked by hand (1.0, 2.0, 3.0, 0.5, 1.5, -1.0) --
// not generated by this project's own RTL, so this is a genuine
// external check, not a tautology.
//
// FP0-7 are loaded directly via a hierarchical backdoor write (this
// project has no other way to load an EXACT, arbitrary extended-
// precision bit pattern yet -- Phase 3's own opclass 010/011 external-
// transfer dialog is still a raw-bytes stub, not real format
// conversion, so it can't be used to construct a precise test operand
// until Phase 6 lands real conversion).

module m68882_apu_tb;

    logic clk_4x = 1'b0;
    logic rst_n  = 1'b0;

    logic [4:0]  a      = 5'h00;
    logic        size_n = 1'b1;
    logic        as_n   = 1'b1;
    logic        cs_n   = 1'b1;
    logic        rw     = 1'b1;
    logic        ds_n   = 1'b1;
    wire         dsack0_n;
    wire         dsack1_n;
    wire         sense_n;

    logic [31:0] d_drv    = 32'h0;
    logic        d_drv_en = 1'b0;
    wire  [31:0] d = d_drv_en ? d_drv : 32'bz;

    always #5 clk_4x = ~clk_4x;

    m68882_top u_top (
        .clk_4x   (clk_4x),
        .rst_n    (rst_n),
        .a        (a),
        .d        (d),
        .size_n   (size_n),
        .as_n     (as_n),
        .cs_n     (cs_n),
        .rw       (rw),
        .ds_n     (ds_n),
        .dsack0_n (dsack0_n),
        .dsack1_n (dsack1_n),
        .sense_n  (sense_n)
    );

    int pass_count = 0;
    int fail_count = 0;

    task automatic check(input logic cond, input string msg);
        if (cond) begin
            pass_count++;
            $display("PASS: %s", msg);
        end else begin
            fail_count++;
            $display("FAIL: %s", msg);
        end
    endtask

    // Phase 9d: FSIN/FCOS are the first genuinely APPROXIMATED op this
    // project implements (see fp_sincos's own header comment in
    // rtl/m68882_apu.sv) -- exact bit-for-bit comparison against an
    // independently-computed reference isn't the right check (nor is it
    // what real silicon itself guarantees, per Section 4.3's own
    // documented "typical error bound of approximately 64 units in the
    // last place"). This task compares sign+exponent exactly (a real
    // mismatch there is always a genuine bug, never rounding noise) and
    // the 64-bit mantissa to within a fixed ULP tolerance.
    task automatic check_close(
        input logic [95:0] actual, input logic [95:0] expected,
        input int ulp_tol, input string msg
    );
        logic [15:0] a_se, e_se;
        logic [63:0] a_m, e_m;
        longint      diff;
        a_se = actual[95:80];   e_se = expected[95:80];
        a_m  = actual[63:0];    e_m  = expected[63:0];
        diff = longint'(a_m) - longint'(e_m);
        if (diff < 0) diff = -diff;
        check((a_se == e_se) && (diff <= ulp_tol),
              $sformatf("%s (sign/exp %s, mantissa diff %0d ULP, tol %0d)",
                        msg, (a_se == e_se) ? "match" : "MISMATCH", diff, ulp_tol));
    endtask

    task automatic run_cycle(
        input  logic [3:0]  sel_a4_a1,
        input  logic        is_write,
        input  logic [31:0] wdata,
        output logic [31:0] rdata
    );
        int wait_ticks;
        @(posedge clk_4x);
        a      = {sel_a4_a1, 1'b1}; // 32-bit port throughout
        rw     = !is_write;
        if (is_write) begin
            d_drv_en = 1'b1;
            d_drv    = wdata;
        end else begin
            d_drv_en = 1'b0;
        end
        cs_n = 1'b0;
        as_n = 1'b0;
        ds_n = 1'b0;

        wait_ticks = 0;
        while (dsack0_n && dsack1_n && wait_ticks < 60) begin
            @(posedge clk_4x);
            wait_ticks++;
        end
        rdata = d;

        @(posedge clk_4x);
        cs_n     = 1'b1;
        as_n     = 1'b1;
        ds_n     = 1'b1;
        d_drv_en = 1'b0;
        repeat (2) @(posedge clk_4x);
    endtask

    function automatic logic [31:0] cmd_word(
        logic [2:0] opclass, logic [2:0] rx, logic [2:0] ry, logic [6:0] ext
    );
        return {opclass, rx, ry, ext, 16'h0};
    endfunction

    // Known-good extended-precision constants (sign|exp15|reserved16|mantissa64)
    localparam logic [95:0] EXT_1_0  = 96'h3fff_0000_8000_0000_0000_0000;
    localparam logic [95:0] EXT_2_0  = 96'h4000_0000_8000_0000_0000_0000;
    localparam logic [95:0] EXT_3_0  = 96'h4000_0000_c000_0000_0000_0000;
    localparam logic [95:0] EXT_0_5  = 96'h3ffe_0000_8000_0000_0000_0000;
    localparam logic [95:0] EXT_1_5  = 96'h3fff_0000_c000_0000_0000_0000;
    localparam logic [95:0] EXT_N1_0 = 96'hbfff_0000_8000_0000_0000_0000;
    localparam logic [95:0] EXT_4_0  = 96'h4001_0000_8000_0000_0000_0000;
    localparam logic [95:0] EXT_6_0  = 96'h4001_0000_c000_0000_0000_0000;
    localparam logic [95:0] EXT_2_25 = 96'h4000_0000_9000_0000_0000_0000;
    localparam logic [95:0] EXT_N3_0 = 96'hc000_0000_c000_0000_0000_0000;
    localparam logic [95:0] EXT_0_25 = 96'h3ffd_0000_8000_0000_0000_0000;
    localparam logic [95:0] EXT_N0_75 = 96'hbffe_0000_c000_0000_0000_0000;
    localparam logic [95:0] EXT_12_0  = 96'h4002_0000_c000_0000_0000_0000;
    localparam logic [95:0] EXT_N8_0  = 96'hc002_0000_8000_0000_0000_0000;
    localparam logic [95:0] EXT_N4_0  = 96'hc001_0000_8000_0000_0000_0000;
    localparam logic [95:0] EXT_7_0   = 96'h4001_0000_e000_0000_0000_0000;
    localparam logic [95:0] EXT_10_0  = 96'h4002_0000_a000_0000_0000_0000;
    localparam logic [95:0] EXT_0_001 = 96'h3ff5_0000_8312_6e97_8d4f_df3b;

    logic [31:0] rd;

    task automatic load_fp(input int idx, input logic [95:0] val);
        u_top.u_proto.u_regfile.fp_r[idx] = val;
    endtask

    // Phase 6: Command CIR dispatch now REQUIRES the mandatory Instruction
    // Address CIR write next (otherwise proto_violation_r pulses and the
    // dialog never leaves ST_WAIT_IADDR), and every opclass-000 op
    // (FADD/FSUB/FMUL/FDIV/FSQRT/FCMP/FABS/FNEG/FTST/FMOVE) commits only
    // after a genuine multi-cycle APU pipeline latency
    // (m68882_proto.sv's own apu_latency(), Phase 9: real Table 8-3
    // cycle counts -- NONE of these ops are actually zero-cycle on real
    // silicon) -- a fixed "repeat(2)" is no longer enough for any of
    // them. Poll the real pipeline-occupancy registers instead of
    // hardcoding a cycle count.
    task automatic dispatch(input logic [31:0] cmdw);
        logic [31:0] rd2;
        int wait_ticks;
        run_cycle(CIR_COMMAND, 1'b1, cmdw, rd2);
        run_cycle(CIR_INSTRADDR, 1'b1, 32'h0000_2000, rd2);
        wait_ticks = 0;
        while ((u_top.u_proto.slotA_valid_r || u_top.u_proto.slotB_valid_r) && wait_ticks < 3000) begin
            @(posedge clk_4x);
            wait_ticks++;
        end
        repeat (2) @(posedge clk_4x);
    endtask

    // Same as dispatch(), but reports the real elapsed clk_4x tick count
    // from "instruction address ack" to "slot pipeline empty" -- for a
    // dedicated cycle-accuracy check (mirrors the timing checks already
    // done in tb/m68882_pipeline_tb.sv, e.g. its own FDIV 432-tick
    // check) rather than the ordinary functional dispatch() above,
    // which only cares that the wait eventually terminates.
    task automatic dispatch_timed(input logic [31:0] cmdw, output int ticks);
        logic [31:0] rd2;
        run_cycle(CIR_COMMAND, 1'b1, cmdw, rd2);
        run_cycle(CIR_INSTRADDR, 1'b1, 32'h0000_2000, rd2);
        ticks = 0;
        while ((u_top.u_proto.slotA_valid_r || u_top.u_proto.slotB_valid_r) && ticks < 3000) begin
            @(posedge clk_4x);
            ticks++;
        end
        repeat (2) @(posedge clk_4x);
    endtask

    // Shares dispatch()'s own drain-wait logic, for a test that dispatched
    // via raw run_cycle calls directly (to observe mid-flight state) and
    // now just needs to wait for the already-in-flight op to commit.
    task automatic wait_ticks_apu_drain();
        int wait_ticks;
        wait_ticks = 0;
        while ((u_top.u_proto.slotA_valid_r || u_top.u_proto.slotB_valid_r) && wait_ticks < 3000) begin
            @(posedge clk_4x);
            wait_ticks++;
        end
        repeat (2) @(posedge clk_4x);
    endtask

    initial begin
        repeat (4) @(posedge clk_4x);
        rst_n = 1'b1;
        repeat (4) @(posedge clk_4x);

        // ── FADD: FP0=1.0, FP1=2.0 -> FP1 = 3.0 ─────────────────────────
        load_fp(0, EXT_1_0);
        load_fp(1, EXT_2_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h22)); // FADD
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_3_0, "FADD: 1.0 + 2.0 == 3.0");
        check(u_top.u_proto.u_regfile.fpsr_r[27:24] == 4'b0000,
              "FADD: condition codes clear for a positive nonzero result");

        // ── FSUB: FP0=1.0, FP1=3.0 -> FP1 = 3.0 - 1.0 = 2.0 ─────────────
        load_fp(0, EXT_1_0);
        load_fp(1, EXT_3_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h28)); // FSUB
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_2_0, "FSUB: 3.0 - 1.0 == 2.0");

        // ── FADD with a carry-out normalization: 0.5 + 0.5 = 1.0 ────────
        load_fp(0, EXT_0_5);
        load_fp(1, EXT_0_5);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h22)); // FADD
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_1_0, "FADD: 0.5 + 0.5 == 1.0 (carry-out renormalization)");

        // ── FADD: 1.0 + (-1.0) = 0.0, condition code Z set ──────────────
        load_fp(0, EXT_1_0);
        load_fp(1, EXT_N1_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h22)); // FADD
        check(u_top.u_proto.u_regfile.fp_r[1][94:0] == 95'h0, "FADD: 1.0 + (-1.0) == 0.0 (magnitude bits)");
        check(u_top.u_proto.u_regfile.fpsr_r[26] == 1'b1, "FADD: Z condition code set for a zero result");

        // ── FSUB: 1.5 - 0.5 = 1.0 (unequal exponents, real alignment) ───
        load_fp(0, EXT_0_5);
        load_fp(1, EXT_1_5);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h28)); // FSUB
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_1_0, "FSUB: 1.5 - 0.5 == 1.0 (exponent alignment)");

        // ── Negative result: FSUB 1.0 - 2.0 = -1.0, N condition code ────
        load_fp(0, EXT_2_0);
        load_fp(1, EXT_1_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h28)); // FSUB
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_N1_0, "FSUB: 1.0 - 2.0 == -1.0");
        check(u_top.u_proto.u_regfile.fpsr_r[27] == 1'b1, "FSUB: N condition code set for a negative result");

        // ── FMUL: 2.0 * 2.0 = 4.0 (product exactly at a power of 2) ─────
        load_fp(0, EXT_2_0);
        load_fp(1, EXT_2_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h23)); // FMUL
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_4_0, "FMUL: 2.0 * 2.0 == 4.0");

        // ── FMUL: 2.0 * 3.0 = 6.0 (product needs the [2,4) renormalization) ──
        load_fp(0, EXT_2_0);
        load_fp(1, EXT_3_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h23)); // FMUL
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_6_0, "FMUL: 2.0 * 3.0 == 6.0");

        // ── FMUL: 1.5 * 1.5 = 2.25 (no renormalization needed) ───────────
        load_fp(0, EXT_1_5);
        load_fp(1, EXT_1_5);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h23)); // FMUL
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_2_25, "FMUL: 1.5 * 1.5 == 2.25");

        // ── FMUL: sign combination, -1.0 * 3.0 = -3.0 ────────────────────
        load_fp(0, EXT_N1_0);
        load_fp(1, EXT_3_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h23)); // FMUL
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_N3_0, "FMUL: -1.0 * 3.0 == -3.0");
        check(u_top.u_proto.u_regfile.fpsr_r[27] == 1'b1, "FMUL: N condition code set for a negative product");

        // ── FMUL: 0.5 * 0.5 = 0.25 (both exponents below bias) ───────────
        load_fp(0, EXT_0_5);
        load_fp(1, EXT_0_5);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h23)); // FMUL
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_0_25, "FMUL: 0.5 * 0.5 == 0.25");

        // ── FDIV: 4.0 / 2.0 = 2.0 (exact, ratio >= 1 branch) ─────────────
        load_fp(0, EXT_2_0);
        load_fp(1, EXT_4_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h20)); // FDIV
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_2_0, "FDIV: 4.0 / 2.0 == 2.0");

        // ── FDIV: 3.0 / 2.0 = 1.5 (ratio < 1 branch on the mantissa divide) ──
        load_fp(0, EXT_2_0);
        load_fp(1, EXT_3_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h20)); // FDIV
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_1_5, "FDIV: 3.0 / 2.0 == 1.5");

        // ── FDIV: 6.0 / 2.0 = 3.0 ────────────────────────────────────────
        load_fp(0, EXT_2_0);
        load_fp(1, EXT_6_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h20)); // FDIV
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_3_0, "FDIV: 6.0 / 2.0 == 3.0");

        // ── FDIV: -6.0 / 2.0 = -3.0 (sign combination) ──────────────────
        load_fp(0, EXT_2_0);
        load_fp(1, {1'b1, EXT_6_0[94:0]}); // -6.0
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h20)); // FDIV
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_N3_0, "FDIV: -6.0 / 2.0 == -3.0");

        // ── FDIV: 1.0 / 0.0 -> signed Infinity, DZ flag set ──────────────
        load_fp(0, 96'h0); // +0.0
        load_fp(1, EXT_1_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h20)); // FDIV
        check(u_top.u_proto.u_regfile.fp_r[1] == {1'b0, 15'h7FFF, 16'h0, 64'h8000_0000_0000_0000},
              "FDIV: 1.0 / 0.0 == +Infinity");
        check(u_top.u_proto.u_regfile.fpsr_r[10] == 1'b1, "FDIV: DZ exception-status bit set for divide-by-zero");

        // ── FABS: |-3.0| = 3.0 (source in RX, result to RY) ──────────────
        load_fp(0, EXT_N3_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h18)); // FABS
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_3_0, "FABS: |-3.0| == 3.0");

        // ── Phase 9 regression: FABS genuinely occupies a real APU
        // pipeline slot now (Table 8-3: 38 real cycles, NOT zero) --
        // confirmed by observing it still IN FLIGHT (slotA_valid_r) right
        // after dispatch, well before its own real latency could have
        // already elapsed. Uses raw run_cycle (not dispatch(), which
        // itself waits for the pipeline to drain) specifically to catch
        // this mid-flight state.
        load_fp(0, EXT_N3_0);
        run_cycle(CIR_COMMAND, 1'b1, cmd_word(3'b000, 3'd0, 3'd1, 7'h18), rd); // FABS
        run_cycle(CIR_INSTRADDR, 1'b1, 32'h0000_3000, rd);
        run_cycle(CIR_RESPONSE, 1'b0, 32'h0, rd);
        check(u_top.u_proto.slotA_valid_r && u_top.u_proto.slotA_op_r == 7'h18,
              "Phase 9: FABS genuinely occupies slot A immediately after dispatch -- not instant on real silicon (Table 8-3)");
        wait_ticks_apu_drain();
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_3_0, "Phase 9: FABS eventually commits the same correct result: |-3.0| == 3.0");

        // ── FABS: |3.0| = 3.0 (already positive, no change in sign) ─────
        load_fp(0, EXT_3_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h18)); // FABS
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_3_0, "FABS: |3.0| == 3.0");

        // ── FNEG: -(2.0) = -2.0 ───────────────────────────────────────────
        load_fp(0, EXT_2_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1A)); // FNEG
        check(u_top.u_proto.u_regfile.fp_r[1] == {1'b1, EXT_2_0[94:0]}, "FNEG: -(2.0) == -2.0");

        // ── FNEG: -(-1.0) = 1.0 (double negation) ────────────────────────
        load_fp(0, EXT_N1_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1A)); // FNEG
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_1_0, "FNEG: -(-1.0) == 1.0");

        // ── FCMP: destination register (RY) is never written ────────────
        load_fp(0, EXT_2_0);
        load_fp(1, EXT_3_0); // dest pre-loaded with a sentinel value
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h38)); // FCMP
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_3_0, "FCMP: destination register FP1 is never written");

        load_fp(0, EXT_2_0);
        load_fp(1, EXT_2_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h38)); // FCMP: FP1(2.0) vs 2.0
        check(u_top.u_proto.u_regfile.fpsr_r[26] == 1'b1, "FCMP: Z condition code set when both operands are equal");

        load_fp(0, EXT_3_0);
        load_fp(1, EXT_2_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h38)); // FCMP: FP1(2.0) vs 3.0 -> 2.0-3.0<0
        check(u_top.u_proto.u_regfile.fpsr_r[27] == 1'b1, "FCMP: N condition code set when FPn < source");

        // ── FTST: tests the SOURCE operand alone, sets condition codes ───
        load_fp(0, 96'h0); // +0.0
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h3A)); // FTST +0.0
        check(u_top.u_proto.u_regfile.fpsr_r[26] == 1'b1, "FTST: Z condition code set for a zero source operand");

        load_fp(0, EXT_N1_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h3A)); // FTST -1.0
        check(u_top.u_proto.u_regfile.fpsr_r[27] == 1'b1, "FTST: N condition code set for a negative source operand");

        // ── FSQRT: sqrt(4.0) = 2.0 (even exponent, exact) ────────────────
        load_fp(0, EXT_4_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h04)); // FSQRT
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_2_0, "FSQRT: sqrt(4.0) == 2.0");

        // ── FSQRT: sqrt(1.0) = 1.0 (odd exponent path: exp(1.0)=0, even -- ─
        // use sqrt(2.25)=1.5 instead to exercise a non-trivial mantissa) ──
        load_fp(0, EXT_2_25);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h04)); // FSQRT
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_1_5, "FSQRT: sqrt(2.25) == 1.5");

        // ── FSQRT: sqrt(9.0) = 3.0 (odd real exponent: 9.0 has exp=3) ────
        load_fp(0, 96'h4002_0000_9000_0000_0000_0000); // 9.0
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h04)); // FSQRT
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_3_0, "FSQRT: sqrt(9.0) == 3.0 (odd-exponent path)");

        // ── FSQRT: sqrt(-4.0) -> NaN, OPERR set ──────────────────────────
        load_fp(0, {1'b1, EXT_4_0[94:0]}); // -4.0
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h04)); // FSQRT
        check(u_top.u_proto.u_regfile.fpsr_r[24] == 1'b1, "FSQRT: NAN condition code set for sqrt of a negative operand");
        check(u_top.u_proto.u_regfile.fpsr_r[13] == 1'b1, "FSQRT: OPERR exception-status bit set for sqrt of a negative operand");

        // ── FSQRT: sqrt(+0.0) = +0.0 ──────────────────────────────────────
        load_fp(0, 96'h0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h04)); // FSQRT
        check(u_top.u_proto.u_regfile.fp_r[1] == 96'h0, "FSQRT: sqrt(+0.0) == +0.0");

        // ── Phase 4d: SNAN detection ──────────────────────────────────────
        // Signaling NaN: exp=0x7FFF, mantissa leading fraction bit (bit62)
        // clear (Section 3.5.4) -- 0x8000000000000001 (bit63=1, bit62=0,
        // a nonzero fraction bit to distinguish from Infinity).
        load_fp(0, {1'b0, 15'h7FFF, 16'h0, 64'h8000_0000_0000_0001}); // sNaN
        load_fp(1, EXT_1_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h22)); // FADD
        check(u_top.u_proto.u_regfile.fpsr_r[14] == 1'b1, "Phase 4d: SNAN exception-status bit set for a signaling NaN input");
        check(u_top.u_proto.u_regfile.fpsr_r[7] == 1'b1, "Phase 4d: AEXC IOP bit set (SNAN contributes to IOP)");

        repeat (4) @(posedge clk_4x);

        // ── Phase 4d: INEX2 (inexact result) via FDIV 1.0/3.0 ────────────
        load_fp(0, {1'b0, 15'h3FFF + 15'd1, 16'h0, 64'hC000_0000_0000_0000}); // 3.0 (source)
        load_fp(1, EXT_1_0); // FPn (dest)
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h20)); // FDIV: FP1 = 1.0/3.0
        check(u_top.u_proto.u_regfile.fpsr_r[9] == 1'b1, "Phase 4d: INEX2 exception-status bit set for an inexact FDIV result");
        check(u_top.u_proto.u_regfile.fpsr_r[3] == 1'b1, "Phase 4d: AEXC INEX bit set (INEX2 contributes to AEXC INEX)");

        repeat (4) @(posedge clk_4x);

        // ── Phase 4d: OVFL via FADD pushing the exponent past 32767 ──────
        load_fp(0, {1'b0, 15'd32766, 16'h0, 64'h8000_0000_0000_0000});
        load_fp(1, {1'b0, 15'd32766, 16'h0, 64'h8000_0000_0000_0000});
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h22)); // FADD (doubles -> exponent+1 overflow)
        check(u_top.u_proto.u_regfile.fpsr_r[12] == 1'b1, "Phase 4d: OVFL exception-status bit set on exponent overflow");
        check(u_top.u_proto.u_regfile.fpsr_r[6] == 1'b1, "Phase 4d: AEXC OVFL bit set");
        check(u_top.u_proto.u_regfile.fp_r[1] == {1'b0, 15'h7FFF, 16'h0, 64'h8000_0000_0000_0000},
              "Phase 4d: overflowed result saturates to +Infinity");

        repeat (4) @(posedge clk_4x);

        // ── Phase 4d: UNFL (+ INEX2) via FMUL pushing the exponent below 1 ──
        load_fp(0, {1'b0, 15'd10, 16'h0, 64'hC000_0000_0000_0001}); // tiny, non-power-of-2 mantissa
        load_fp(1, {1'b0, 15'd10, 16'h0, 64'hC000_0000_0000_0001});
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h23)); // FMUL
        check(u_top.u_proto.u_regfile.fpsr_r[11] == 1'b1, "Phase 4d: UNFL exception-status bit set on exponent underflow");
        check(u_top.u_proto.u_regfile.fp_r[1] == 96'h0, "Phase 4d: underflowed result flushes to zero");

        repeat (4) @(posedge clk_4x);

        // ── Phase 4d: AEXC is sticky across separate, unrelated operations ──
        load_fp(0, 96'h0); // +0.0
        load_fp(1, EXT_1_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h20)); // FDIV 1.0/0.0 -> DZ
        check(u_top.u_proto.u_regfile.fpsr_r[4] == 1'b1, "Phase 4d: AEXC DZ bit set after a divide-by-zero");
        load_fp(0, EXT_1_0);
        load_fp(1, EXT_2_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h22)); // an unrelated, exact FADD
        check(u_top.u_proto.u_regfile.fpsr_r[4] == 1'b1,
              "Phase 4d: AEXC DZ bit stays set (sticky) after a later, unrelated operation");
        check(u_top.u_proto.u_regfile.fpsr_r[10] == 1'b0,
              "Phase 4d: EXC DZ bit itself is NOT sticky -- cleared by the later, unrelated operation");

        // ── Phase 9: FMOVE (register-to-register, ext=$00) -- a real bug
        // fix. Previously this extension code fell into an unconditional
        // "no-op stub" fallback and silently did nothing at all (never
        // caught before since no existing test dispatched it and checked
        // the result); it's a real, defined instruction (Table 4-13:
        // "$00 FMOVE to FPn") that must copy the source register to the
        // destination, same as any other opclass-000 op, and now goes
        // through the real pipeline with its own genuine Table 8-3
        // latency (21 cycles).
        load_fp(0, EXT_N3_0);
        load_fp(1, EXT_1_0); // dest sentinel, != -3.0
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h00)); // FMOVE FP0,FP1
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_N3_0, "Phase 9: FMOVE FP0,FP1 copies the source value (-3.0) to the destination");
        check(u_top.u_proto.u_regfile.fpsr_r[27] == 1'b1, "Phase 9: FMOVE sets the N condition code for a negative moved value");

        // ── Phase 9b: FGETMAN ($1F) -- extract the normalized mantissa in
        // [1,2) as a float. Not in Musashi's own opcode set at all (never
        // implemented there), so verified here directly instead of via
        // the Musashi cosim battery.
        load_fp(0, EXT_N8_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1F)); // FGETMAN -8.0
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_N1_0, "Phase 9b: FGETMAN(-8.0) == -1.0 (sign preserved, mantissa already 1.0)");

        load_fp(0, EXT_6_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1F)); // FGETMAN 6.0
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_1_5, "Phase 9b: FGETMAN(6.0) == 1.5 (6.0 = 1.5 * 2^2)");

        // ── Phase 9b: FSCALE ($26) -- dyadic (RX=scale factor, RY=dest
        // value being scaled). Also not in Musashi's own opcode set.
        load_fp(0, EXT_2_0); // scale factor: trunc(2.0) = 2
        load_fp(1, EXT_3_0); // value being scaled (and overwritten)
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h26)); // FSCALE
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_12_0, "Phase 9b: FSCALE(2.0, 3.0) == 3.0 * 2^2 == 12.0");

        load_fp(0, EXT_N1_0); // scale factor: trunc(-1.0) = -1
        load_fp(1, EXT_3_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h26)); // FSCALE
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_1_5, "Phase 9b: FSCALE(-1.0, 3.0) == 3.0 * 2^-1 == 1.5");

        // ── Phase 9b: FGETEXP on a negative and a zero source --
        // deliberately EXCLUDED from the Musashi cosim battery (a real,
        // confirmed Musashi bug: m68kfpu.c's own FGETEXP reads
        // `source.high` -- the sign bit AND the exponent together --
        // straight into a signed 16-bit temp without masking the sign
        // off first, corrupting the result for any negative or zero
        // source; confirmed by direct inspection of that one line, not
        // assumed). This project's own rtl/m68882_apu.sv correctly
        // extracts only the 15-bit exponent field (fpx_t's own `.exp`),
        // independent of the source's sign -- verified here directly.
        load_fp(0, EXT_N4_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1E)); // FGETEXP -4.0
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_2_0,
              "Phase 9b: FGETEXP(-4.0) == +2.0 (the exponent's own sign is independent of the source's sign -- NOT the Musashi bug's -32766-ish garbage)");

        load_fp(0, 96'h0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1E)); // FGETEXP 0.0
        check(u_top.u_proto.u_regfile.fp_r[1] == 96'h0, "Phase 9b: FGETEXP(0.0) == 0.0 (not the Musashi bug's garbage result)");

        // ── Phase 9b: FINTRZ(-0.75) -- deliberately EXCLUDED from the
        // Musashi cosim battery: Musashi's own FINT/FINTRZ round-trip
        // through a plain sint32 intermediate (floatx80_to_int32[_
        // round_to_zero] then int32_to_floatx80), and a 32-bit integer
        // has no negative-zero representation, so any negative source
        // that truncates to zero necessarily comes back +0.0 there
        // regardless of what real hardware does. This project's own RTL
        // never goes through an integer intermediate and preserves the
        // sign, matching IEEE 754-2008's own roundToIntegralTowardZero
        // (explicitly sign-preserving for a zero result).
        load_fp(0, EXT_N0_75);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h03)); // FINTRZ -0.75
        check(u_top.u_proto.u_regfile.fp_r[1] == {1'b1, 95'h0}, "Phase 9b: FINTRZ(-0.75) == -0.0 (sign preserved on truncation to zero)");
        check(u_top.u_proto.u_regfile.fpsr_r[26] == 1'b1, "Phase 9b: FINTRZ(-0.75) sets the Z condition code (a signed zero is still zero)");

        // ── Phase 9c: FSGLDIV ($24) / FSGLMUL ($27) -- single-precision-
        // rounded divide/multiply.
        load_fp(0, EXT_2_0);
        load_fp(1, EXT_3_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h24)); // FSGLDIV: 3.0/2.0
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_1_5, "Phase 9c: FSGLDIV(2.0, 3.0) == 3.0/2.0 == 1.5 (exact in single precision)");

        load_fp(0, EXT_2_0);
        load_fp(1, EXT_3_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h27)); // FSGLMUL: 2.0*3.0
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_6_0, "Phase 9c: FSGLMUL(2.0, 3.0) == 2.0*3.0 == 6.0");

        // ── Phase 9c: FMOD ($21) vs FREM ($25) -- the real, documented
        // distinction (truncated vs round-to-nearest quotient) that
        // Musashi's own FMOD/FREM implementation FAILS to make (a third
        // confirmed Musashi bug -- m68kfpu.c's own `case 0x21: FMOD`
        // calls the identical `floatx80_rem` FREM's own `case 0x25`
        // calls, so Musashi's FMOD is silently just an alias for FREM).
        // 7.0/2.0 = 3.5 exactly -- FMOD truncates the quotient to 3,
        // FREM rounds it to nearest-even, 4 -- genuinely different
        // results (+1.0 vs -1.0), not just different intermediate
        // rounding noise.
        load_fp(0, EXT_2_0); // source (divisor)
        load_fp(1, EXT_7_0); // dest (dividend)
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h21)); // FMOD: 7.0 mod 2.0, N=trunc(3.5)=3
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_1_0, "Phase 9c: FMOD(2.0, 7.0) == 7.0 - 2.0*trunc(3.5) == 7.0 - 2.0*3 == 1.0");
        check(u_top.u_proto.u_regfile.fpsr_r[22:16] == 7'd3, "Phase 9c: FMOD(2.0, 7.0) quotient byte == 3 (the truncated quotient, unsigned bits)");
        check(u_top.u_proto.u_regfile.fpsr_r[23] == 1'b0, "Phase 9c: FMOD(2.0, 7.0) quotient sign == 0 (positive/positive division)");

        load_fp(0, EXT_2_0);
        load_fp(1, EXT_7_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h25)); // FREM: 7.0 mod 2.0, N=round(3.5)=4 (ties to even)
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_N1_0, "Phase 9c: FREM(2.0, 7.0) == 7.0 - 2.0*round(3.5) == 7.0 - 2.0*4 == -1.0 -- genuinely different from FMOD's own +1.0 (NOT the Musashi bug's aliasing)");
        check(u_top.u_proto.u_regfile.fpsr_r[22:16] == 7'd4, "Phase 9c: FREM(2.0, 7.0) quotient byte == 4 (the rounded quotient)");

        // Quotient sign = XOR of operand signs (Section 2.3.2, confirmed
        // directly) -- verify with a negative dividend.
        load_fp(0, EXT_2_0);
        load_fp(1, {1'b1, EXT_7_0[94:0]}); // -7.0
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h21)); // FMOD: -7.0 mod 2.0
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_N1_0, "Phase 9c: FMOD(2.0, -7.0) == -7.0 - 2.0*trunc(-3.5) == -7.0 - 2.0*(-3) == -1.0");
        check(u_top.u_proto.u_regfile.fpsr_r[23] == 1'b1, "Phase 9c: FMOD(2.0, -7.0) quotient sign == 1 (positive/negative division)");

        // ── Phase 9d: FSIN/FCOS ──────────────────────────────────────
        // Reference values below computed independently in Python via a
        // Decimal-precision (80-digit) Taylor series summed to full
        // extended-precision convergence (NOT Python's own math.sin/cos,
        // which is only IEEE double, i.e. ~16 decimal digits -- too
        // coarse a reference for an 80-bit-extended result), then
        // rounded to the nearest extended-precision bit pattern the
        // same way every other constant in this file was derived.
        // ulp_tol=4096 matches Section 4.3's own documented worst-case
        // accuracy bound for real 68881/2 silicon ("4096 units in the
        // last place") -- this project's own 9-term-Taylor
        // implementation measures far tighter than that in practice
        // (single-digit-to-low-double-digit ULP for these vectors), but
        // the manual's own real-hardware bound is the correct thing to
        // gate the test on, not an arbitrarily tighter number this
        // project's own implementation happens to hit today.
        load_fp(0, EXT_0_5);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h0E)); // FSIN(0.5)
        check_close(u_top.u_proto.u_regfile.fp_r[1], 96'h3ffd_0000_f57743a2582f7f44,
                    4096, "Phase 9d: FSIN(0.5) ~= 0.4794255386...");

        load_fp(0, EXT_0_5);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1D)); // FCOS(0.5)
        check_close(u_top.u_proto.u_regfile.fp_r[1], 96'h3ffe_0000_e0a94032dbea7cee,
                    4096, "Phase 9d: FCOS(0.5) ~= 0.8775825619...");

        load_fp(0, EXT_1_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h0E)); // FSIN(1.0)
        check_close(u_top.u_proto.u_regfile.fp_r[1], 96'h3ffe_0000_d76aa47848677021,
                    4096, "Phase 9d: FSIN(1.0) ~= 0.8414709848...");

        load_fp(0, EXT_1_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1D)); // FCOS(1.0)
        check_close(u_top.u_proto.u_regfile.fp_r[1], 96'h3ffe_0000_8a51407da8345c92,
                    4096, "Phase 9d: FCOS(1.0) ~= 0.5403023059...");

        load_fp(0, EXT_2_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h0E)); // FSIN(2.0)
        check_close(u_top.u_proto.u_regfile.fp_r[1], 96'h3ffe_0000_e8c7b7568da22efd,
                    4096, "Phase 9d: FSIN(2.0) ~= 0.9092974268...");

        load_fp(0, EXT_2_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1D)); // FCOS(2.0)
        check_close(u_top.u_proto.u_regfile.fp_r[1], 96'hbffd_0000_d51132ba9b902522,
                    4096, "Phase 9d: FCOS(2.0) ~= -0.4161468365...");

        load_fp(0, EXT_N1_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h0E)); // FSIN(-1.0), sign of source
        check_close(u_top.u_proto.u_regfile.fp_r[1], 96'hbffe_0000_d76aa47848677021,
                    4096, "Phase 9d: FSIN(-1.0) ~= -0.8414709848...");

        load_fp(0, EXT_10_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h0E)); // FSIN(10.0), argument reduction exercised (k=6)
        check_close(u_top.u_proto.u_regfile.fp_r[1], 96'hbffe_0000_8b44f7af9a7a92ce,
                    4096, "Phase 9d: FSIN(10.0) ~= -0.5440211109... (argument reduction, k=6)");

        load_fp(0, EXT_10_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1D)); // FCOS(10.0)
        check_close(u_top.u_proto.u_regfile.fp_r[1], 96'hbffe_0000_d6cd64486358f905,
                    4096, "Phase 9d: FCOS(10.0) ~= -0.8390715291... (argument reduction, k=6)");

        // Operation Table special cases (Section 4, confirmed directly):
        // FCOS(+-0.0) = +1.0; FSIN(+-0.0) = +-0.0 (sign preserved);
        // FSIN/FCOS(+-inf) = NaN + OPERR. All exact, not tolerance-based.
        load_fp(0, 96'h0000_0000_0000_0000_0000_0000); // +0.0
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h0E)); // FSIN(+0.0)
        check(u_top.u_proto.u_regfile.fp_r[1] == 96'h0, "Phase 9d: FSIN(+0.0) == +0.0");

        load_fp(0, 96'h8000_0000_0000_0000_0000_0000); // -0.0
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h0E)); // FSIN(-0.0)
        check(u_top.u_proto.u_regfile.fp_r[1] == 96'h8000_0000_0000_0000_0000_0000, "Phase 9d: FSIN(-0.0) == -0.0 (sign preserved)");

        load_fp(0, 96'h0000_0000_0000_0000_0000_0000); // +0.0
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1D)); // FCOS(+0.0)
        check(u_top.u_proto.u_regfile.fp_r[1] == EXT_1_0, "Phase 9d: FCOS(+0.0) == +1.0");

        load_fp(0, 96'h7fff_0000_8000_0000_0000_0000); // +inf
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h0E)); // FSIN(+inf)
        check(u_top.u_proto.u_regfile.fpsr_r[24] == 1'b1, "Phase 9d: FSIN(+inf) NAN condition code set");
        check(u_top.u_proto.u_regfile.fpsr_r[13] == 1'b1, "Phase 9d: FSIN(+inf) OPERR exception-status bit set");

        load_fp(0, 96'h7fff_0000_8000_0000_0000_0000); // +inf
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h1D)); // FCOS(+inf)
        check(u_top.u_proto.u_regfile.fpsr_r[24] == 1'b1, "Phase 9d: FCOS(+inf) NAN condition code set");
        check(u_top.u_proto.u_regfile.fpsr_r[13] == 1'b1, "Phase 9d: FCOS(+inf) OPERR exception-status bit set");

        // ── Phase 9e: FSINCOS ─────────────────────────────────────────
        // The one real op needing TWO register writes -- ext=$32 (top
        // nibble $30-$37 fixed = FSINCOS, low 3 bits = 2 selects FP2 as
        // the cos destination, matching Musashi's own `opmode&7`). Ry=1
        // (FP1) is the usual sin destination. Reference values are the
        // SAME high-precision sin(0.5)/cos(0.5) constants already
        // verified above for FSIN(0.5)/FCOS(0.5).
        load_fp(0, EXT_0_5);
        load_fp(1, 96'h0); // sentinel, must be overwritten with sin(0.5)
        load_fp(2, 96'h0); // sentinel, must be overwritten with cos(0.5)
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h32)); // FSINCOS(0.5), cos->FP2
        check_close(u_top.u_proto.u_regfile.fp_r[1], 96'h3ffd_0000_f57743a2582f7f44,
                    4096, "Phase 9e: FSINCOS(0.5) sin (FP1, the usual Ry dest) ~= 0.4794255386...");
        check_close(u_top.u_proto.u_regfile.fp_r[2], 96'h3ffe_0000_e0a94032dbea7cee,
                    4096, "Phase 9e: FSINCOS(0.5) cos (FP2, the opmode-encoded 2nd dest) ~= 0.8775825619...");
        check(u_top.u_proto.u_regfile.fpsr_r[24] == 1'b0 && u_top.u_proto.u_regfile.fpsr_r[27] == 1'b0,
              "Phase 9e: FSINCOS(0.5) condition codes reflect the SIN result only (matching Musashi's own SET_CONDITION_CODES(REG_FP[dst]))");

        // Real Table 8-3 totals ("FPn to FPm" column, confirmed directly)
        // are FSIN=394 cyc, FSINCOS=454 cyc -- a real 60-cycle (240-tick)
        // difference, entirely attributable to FSINCOS's own extra
        // register write. Rather than pin an exact absolute tick count
        // (which would also bake in this testbench's own CIR-dialog
        // dispatch overhead, not something this check cares about),
        // measure BOTH ops through the identical harness and check their
        // DIFFERENCE against the real, table-derived delta -- this
        // directly tests whether the 2-tick commit sequence's own extra
        // tick lands on the real total, independent of dispatch overhead.
        begin
            int fsin_ticks, fsincos_ticks;
            load_fp(0, EXT_0_5);
            dispatch_timed(cmd_word(3'b000, 3'd0, 3'd1, 7'h0E), fsin_ticks); // FSIN(0.5)
            load_fp(0, EXT_0_5);
            dispatch_timed(cmd_word(3'b000, 3'd0, 3'd1, 7'h32), fsincos_ticks); // FSINCOS(0.5)
            check((fsincos_ticks - fsin_ticks) == 240,
                  $sformatf("Phase 9e: FSINCOS real Table 8-3 timing: %0d ticks (FSINCOS) - %0d ticks (FSIN) = %0d, want exactly 240 (the real 60-cycle Table 8-3 delta x4 -- the 2-tick dual-register commit landing on the real total, not one tick short or one tick over)",
                            fsincos_ticks, fsin_ticks, fsincos_ticks - fsin_ticks));
        end

        // ── Phase 9f: FETOX/FETOXM1/FTWOTOX/FTENTOX (the exponential
        // family, shared fp_exp_core) ───────────────────────────────
        // Reference values independently computed in Python (80-digit
        // Decimal Taylor series -- same methodology as FSIN/FCOS's own
        // reference generation in Phase 9d).
        load_fp(0, EXT_1_0);
        dispatch(cmd_word(3'b000, 3'd0, 3'd1, 7'h10)); // FETOX(1.0) = e
        check_close(u_top.u_proto.u_regfile.fp_r[1], 96'h4000_0000_adf85458a2bb4a9b,
                    4096, "Phase 9f: FETOX(1.0) ~= e = 2.7182818285...");

